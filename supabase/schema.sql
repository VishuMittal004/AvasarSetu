-- ================================================================
-- CareerCompass — Supabase SQL Schema
-- Run this in: Supabase Dashboard → SQL Editor → New Query
-- ================================================================

-- Enable the vector extension (for semantic search later)
CREATE EXTENSION IF NOT EXISTS vector;

-- ================================================================
-- SOURCES  (websites being scraped)
-- ================================================================
CREATE TABLE IF NOT EXISTS sources (
  id                    SERIAL PRIMARY KEY,
  name                  TEXT NOT NULL,
  url                   TEXT NOT NULL UNIQUE,
  type                  TEXT DEFAULT 'government', -- government | psu | private | ngo
  trust_level           TEXT DEFAULT 'unverified', -- verified | unverified
  scrape_interval_hours INT  DEFAULT 24,
  last_scraped_at       TIMESTAMPTZ,
  is_active             BOOLEAN DEFAULT true,
  scrape_config         JSONB DEFAULT '{}'
);

-- One durable record per scheduled/manual ingestion run.
CREATE TABLE IF NOT EXISTS crawl_runs (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  status         TEXT NOT NULL DEFAULT 'running',
  started_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at    TIMESTAMPTZ,
  duration_ms    BIGINT,
  total_fetched  INT NOT NULL DEFAULT 0,
  inserted       INT NOT NULL DEFAULT 0,
  updated        INT NOT NULL DEFAULT 0,
  sync_errors    INT NOT NULL DEFAULT 0,
  summary        JSONB NOT NULL DEFAULT '{}'
);

CREATE TABLE IF NOT EXISTS crawl_source_runs (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id         UUID NOT NULL REFERENCES crawl_runs(id) ON DELETE CASCADE,
  source_name    TEXT NOT NULL,
  status         TEXT NOT NULL,
  records_found  INT NOT NULL DEFAULT 0,
  error_message  TEXT,
  duration_ms    BIGINT,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(run_id, source_name)
);

-- ================================================================
-- OPPORTUNITIES
-- ================================================================
CREATE TABLE IF NOT EXISTS opportunities (
  id                      TEXT PRIMARY KEY,
  type                    TEXT NOT NULL,  -- job | scholarship | scheme | exam | internship | subsidy | pension
  title                   TEXT NOT NULL,
  issuing_authority       TEXT NOT NULL,
  description             TEXT,
  location                TEXT,
  state                   TEXT,
  deadline                TIMESTAMPTZ,
  salary_or_amount        TEXT,
  vacancy_count           INT,
  application_link        TEXT,
  tags                    TEXT[] DEFAULT '{}',
  search_vector           TSVECTOR GENERATED ALWAYS AS (
    to_tsvector('english', coalesce(title, '') || ' ' || coalesce(description, '') || ' ' || coalesce(issuing_authority, ''))
  ) STORED,
  source_id               INT REFERENCES sources(id),
  source_name             TEXT,
  source_url              TEXT,
  source_type             TEXT DEFAULT 'government',
  trust_level             TEXT DEFAULT 'unverified',
  last_verified_at        TIMESTAMPTZ DEFAULT now(),
  extraction_confidence   FLOAT DEFAULT 1.0,
  is_active               BOOLEAN DEFAULT true,
  is_demo                 BOOLEAN DEFAULT false,
  created_at              TIMESTAMPTZ DEFAULT now(),
  updated_at              TIMESTAMPTZ DEFAULT now()
);

-- ================================================================
-- ELIGIBILITY RULES  (1:1 with opportunities)
-- ================================================================
CREATE TABLE IF NOT EXISTS eligibility_rules (
  opportunity_id     TEXT PRIMARY KEY REFERENCES opportunities(id) ON DELETE CASCADE,
  min_age            INT,
  max_age            INT,
  max_income         BIGINT,
  min_experience     INT,
  max_experience     INT,
  required_education TEXT[] DEFAULT '{}',
  required_degrees   TEXT[] DEFAULT '{}',
  required_branches  TEXT[] DEFAULT '{}',
  allowed_categories TEXT[] DEFAULT '{}',
  states             TEXT[] DEFAULT '{}',
  required_skills    TEXT[] DEFAULT '{}'
);

-- ================================================================
-- REQUIRED DOCUMENTS  (many:1 with opportunities)
-- ================================================================
CREATE TABLE IF NOT EXISTS required_documents (
  id              SERIAL PRIMARY KEY,
  opportunity_id  TEXT REFERENCES opportunities(id) ON DELETE CASCADE,
  name            TEXT NOT NULL,
  category        TEXT,
  is_required     BOOLEAN DEFAULT true,
  notes           TEXT
);

-- ================================================================
-- APPLICATION STEPS  (ordered, many:1 with opportunities)
-- ================================================================
CREATE TABLE IF NOT EXISTS application_steps (
  id              SERIAL PRIMARY KEY,
  opportunity_id  TEXT REFERENCES opportunities(id) ON DELETE CASCADE,
  step_order      INT NOT NULL,
  description     TEXT NOT NULL
);

-- ================================================================
-- VECTOR EMBEDDINGS  (for semantic search — populate later)
-- ================================================================
CREATE TABLE IF NOT EXISTS opportunity_embeddings (
  opportunity_id TEXT PRIMARY KEY REFERENCES opportunities(id) ON DELETE CASCADE,
  embedding      VECTOR(768),
  embedded_text  TEXT,
  updated_at     TIMESTAMPTZ DEFAULT now()
);

-- ================================================================
-- AUTO-CREATE PROFILE ON SIGNUP  (Supabase auth trigger)
-- ================================================================
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, email, name)
  VALUES (
    NEW.id,
    NEW.email,
    COALESCE(NULLIF(NEW.raw_user_meta_data ->> 'full_name', ''), NULLIF(NEW.raw_user_meta_data ->> 'name', ''), '')
  )
  ON CONFLICT (id) DO UPDATE
    SET email = EXCLUDED.email,
        name = COALESCE(NULLIF(public.profiles.name, ''), EXCLUDED.name);
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = '';

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- ================================================================
-- SEMANTIC SEARCH FUNCTION  (activate after adding embeddings)
-- ================================================================
CREATE OR REPLACE FUNCTION match_opportunities(
  query_embedding VECTOR(768),
  match_threshold FLOAT DEFAULT 0.7,
  match_count     INT   DEFAULT 50
)
RETURNS TABLE(opportunity_id TEXT, similarity FLOAT) AS $$
  SELECT oe.opportunity_id,
         1 - (oe.embedding <=> query_embedding) AS similarity
  FROM   opportunity_embeddings oe
  JOIN   opportunities o ON o.id = oe.opportunity_id
  WHERE  o.is_active = true
    AND  1 - (oe.embedding <=> query_embedding) > match_threshold
  ORDER  BY similarity DESC
  LIMIT  match_count;
$$ LANGUAGE sql;


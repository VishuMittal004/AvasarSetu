-- ================================================================
-- USER PROFILES  (extends Supabase auth.users)
-- ================================================================
CREATE TABLE IF NOT EXISTS profiles (
  id                    UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  name                  TEXT,
  email                 TEXT,
  phone                 TEXT,
  date_of_birth         DATE,
  gender                TEXT,
  category              TEXT,  -- General | OBC | SC | ST | EWS
  education_level       TEXT,
  degree                TEXT,
  branch                TEXT,
  institution           TEXT,
  graduation_year       INT,
  cgpa                  FLOAT,
  employment_status     TEXT,
  years_of_experience   INT,
  "current_role"        TEXT,
  income                BIGINT DEFAULT 0,
  state                 TEXT,
  district              TEXT,
  skills                TEXT[] DEFAULT '{}',
  interests             TEXT[] DEFAULT '{}',
  preferred_locations   TEXT[] DEFAULT '{}',
  resume_text           TEXT,
  created_at            TIMESTAMPTZ DEFAULT now(),
  updated_at            TIMESTAMPTZ DEFAULT now()
);

-- ================================================================
-- SAVED OPPORTUNITIES
-- ================================================================
CREATE TABLE IF NOT EXISTS saved_opportunities (
  id              UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  user_id         UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  opportunity_id  TEXT NOT NULL REFERENCES opportunities(id) ON DELETE CASCADE,
  status          TEXT DEFAULT 'saved',  -- saved | applied | in-progress | expired
  notes           TEXT,
  saved_at        TIMESTAMPTZ DEFAULT now(),
  UNIQUE(user_id, opportunity_id)
);

-- ================================================================
-- NOTIFICATIONS
-- ================================================================
CREATE TABLE IF NOT EXISTS notifications (
  id              UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  user_id         UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  type            TEXT NOT NULL,  -- deadline | match | system | update
  title           TEXT NOT NULL,
  message         TEXT NOT NULL,
  link            TEXT,
  dedupe_key      TEXT UNIQUE,
  is_read         BOOLEAN DEFAULT false,
  created_at      TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS push_subscriptions (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id         UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  endpoint        TEXT NOT NULL UNIQUE,
  p256dh          TEXT NOT NULL,
  auth            TEXT NOT NULL,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_used_at    TIMESTAMPTZ
);

-- ================================================================
-- USER DOCUMENTS  (checklist state)
-- ================================================================
CREATE TABLE IF NOT EXISTS user_documents (
  id              UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  user_id         UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  document_key    TEXT NOT NULL,
  file_name       TEXT,
  file_size       INT,
  uploaded_at     TIMESTAMPTZ DEFAULT now(),
  UNIQUE(user_id, document_key)
);

-- ================================================================
-- INDEXES  (performance)
-- ================================================================
CREATE INDEX IF NOT EXISTS idx_opportunities_type        ON opportunities(type);
CREATE INDEX IF NOT EXISTS idx_opportunities_state       ON opportunities(state);
CREATE INDEX IF NOT EXISTS idx_opportunities_deadline    ON opportunities(deadline);
CREATE INDEX IF NOT EXISTS idx_opportunities_is_active   ON opportunities(is_active);
CREATE INDEX IF NOT EXISTS idx_opportunities_tags        ON opportunities USING GIN(tags);
CREATE INDEX IF NOT EXISTS idx_eligibility_opp_id       ON eligibility_rules(opportunity_id);
CREATE INDEX IF NOT EXISTS idx_saved_user_id             ON saved_opportunities(user_id);
CREATE INDEX IF NOT EXISTS idx_notifications_user_id     ON notifications(user_id, is_read);
CREATE INDEX IF NOT EXISTS idx_crawl_runs_started_at     ON crawl_runs(started_at DESC);
CREATE INDEX IF NOT EXISTS idx_crawl_source_runs_run_id  ON crawl_source_runs(run_id);
CREATE INDEX IF NOT EXISTS idx_push_subscriptions_user   ON push_subscriptions(user_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_opportunities_source_url_unique
  ON opportunities(source_url) WHERE source_url IS NOT NULL AND source_url <> '';

-- Full-text search index
CREATE INDEX IF NOT EXISTS idx_opportunities_fts ON opportunities USING GIN(search_vector);


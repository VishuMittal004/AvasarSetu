-- Ingestion reliability, duplicate cleanup, and authenticated push delivery.
-- This migration is written for existing projects. Review and run in Supabase SQL Editor.

ALTER TABLE public.opportunities
  ADD COLUMN IF NOT EXISTS search_vector tsvector
  GENERATED ALWAYS AS (
    to_tsvector('english', coalesce(title, '') || ' ' || coalesce(description, '') || ' ' || coalesce(issuing_authority, ''))
  ) STORED;

CREATE INDEX IF NOT EXISTS idx_opportunities_fts
  ON public.opportunities USING GIN (search_vector);

-- Preserve user-owned rows while consolidating legacy duplicate source URLs.
DO $$
DECLARE
  duplicate_row RECORD;
BEGIN
  FOR duplicate_row IN
    SELECT id AS duplicate_id, canonical_id
    FROM (
      SELECT id,
        first_value(id) OVER (
          PARTITION BY source_url
          ORDER BY is_active DESC, last_verified_at DESC NULLS LAST, updated_at DESC NULLS LAST, id
        ) AS canonical_id,
        row_number() OVER (
          PARTITION BY source_url
          ORDER BY is_active DESC, last_verified_at DESC NULLS LAST, updated_at DESC NULLS LAST, id
        ) AS row_number
      FROM public.opportunities
      WHERE source_url IS NOT NULL AND btrim(source_url) <> ''
    ) ranked
    WHERE row_number > 1
  LOOP
    UPDATE public.saved_opportunities canonical_saved
    SET status = CASE
          WHEN canonical_saved.status = 'applied' OR duplicate_saved.status = 'applied' THEN 'applied'
          WHEN canonical_saved.status = 'in-progress' OR duplicate_saved.status = 'in-progress' THEN 'in-progress'
          WHEN canonical_saved.status = 'expired' OR duplicate_saved.status = 'expired' THEN 'expired'
          ELSE coalesce(canonical_saved.status, duplicate_saved.status, 'saved')
        END,
        notes = coalesce(canonical_saved.notes, duplicate_saved.notes)
    FROM public.saved_opportunities duplicate_saved
    WHERE duplicate_saved.opportunity_id = duplicate_row.duplicate_id
      AND canonical_saved.user_id = duplicate_saved.user_id
      AND canonical_saved.opportunity_id = duplicate_row.canonical_id;

    DELETE FROM public.saved_opportunities duplicate_saved
    WHERE duplicate_saved.opportunity_id = duplicate_row.duplicate_id
      AND EXISTS (
        SELECT 1 FROM public.saved_opportunities canonical_saved
        WHERE canonical_saved.user_id = duplicate_saved.user_id
          AND canonical_saved.opportunity_id = duplicate_row.canonical_id
      );

    UPDATE public.saved_opportunities
      SET opportunity_id = duplicate_row.canonical_id
      WHERE opportunity_id = duplicate_row.duplicate_id;

    DELETE FROM public.opportunity_embeddings duplicate_embedding
    WHERE duplicate_embedding.opportunity_id = duplicate_row.duplicate_id
      AND EXISTS (
        SELECT 1 FROM public.opportunity_embeddings canonical_embedding
        WHERE canonical_embedding.opportunity_id = duplicate_row.canonical_id
      );
    UPDATE public.opportunity_embeddings
      SET opportunity_id = duplicate_row.canonical_id
      WHERE opportunity_id = duplicate_row.duplicate_id;

    DELETE FROM public.eligibility_rules duplicate_rule
    WHERE duplicate_rule.opportunity_id = duplicate_row.duplicate_id
      AND EXISTS (
        SELECT 1 FROM public.eligibility_rules canonical_rule
        WHERE canonical_rule.opportunity_id = duplicate_row.canonical_id
      );
    UPDATE public.eligibility_rules
      SET opportunity_id = duplicate_row.canonical_id
      WHERE opportunity_id = duplicate_row.duplicate_id;

    UPDATE public.required_documents
      SET opportunity_id = duplicate_row.canonical_id
      WHERE opportunity_id = duplicate_row.duplicate_id;
    UPDATE public.application_steps
      SET opportunity_id = duplicate_row.canonical_id
      WHERE opportunity_id = duplicate_row.duplicate_id;
    DELETE FROM public.opportunities WHERE id = duplicate_row.duplicate_id;
  END LOOP;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS idx_opportunities_source_url_unique
  ON public.opportunities(source_url)
  WHERE source_url IS NOT NULL AND source_url <> '';

CREATE TABLE IF NOT EXISTS public.crawl_runs (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  status TEXT NOT NULL DEFAULT 'running',
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at TIMESTAMPTZ,
  duration_ms BIGINT,
  total_fetched INT NOT NULL DEFAULT 0,
  inserted INT NOT NULL DEFAULT 0,
  updated INT NOT NULL DEFAULT 0,
  sync_errors INT NOT NULL DEFAULT 0,
  summary JSONB NOT NULL DEFAULT '{}'
);

CREATE TABLE IF NOT EXISTS public.crawl_source_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id UUID NOT NULL REFERENCES public.crawl_runs(id) ON DELETE CASCADE,
  source_name TEXT NOT NULL,
  status TEXT NOT NULL,
  records_found INT NOT NULL DEFAULT 0,
  error_message TEXT,
  duration_ms BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(run_id, source_name)
);

CREATE INDEX IF NOT EXISTS idx_crawl_runs_started_at ON public.crawl_runs(started_at DESC);
CREATE INDEX IF NOT EXISTS idx_crawl_source_runs_run_id ON public.crawl_source_runs(run_id);
ALTER TABLE public.crawl_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.crawl_source_runs ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS crawl_runs_service_only ON public.crawl_runs;
CREATE POLICY crawl_runs_service_only ON public.crawl_runs FOR ALL
  USING (auth.role() = 'service_role') WITH CHECK (auth.role() = 'service_role');
DROP POLICY IF EXISTS crawl_source_runs_service_only ON public.crawl_source_runs;
CREATE POLICY crawl_source_runs_service_only ON public.crawl_source_runs FOR ALL
  USING (auth.role() = 'service_role') WITH CHECK (auth.role() = 'service_role');

ALTER TABLE public.notifications ADD COLUMN IF NOT EXISTS dedupe_key TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS idx_notifications_dedupe_key
  ON public.notifications(dedupe_key) WHERE dedupe_key IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.push_subscriptions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  endpoint TEXT NOT NULL UNIQUE,
  p256dh TEXT NOT NULL,
  auth TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_used_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_push_subscriptions_user ON public.push_subscriptions(user_id);
ALTER TABLE public.push_subscriptions ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS push_subscriptions_own_access ON public.push_subscriptions;
CREATE POLICY push_subscriptions_own_access ON public.push_subscriptions FOR ALL
  USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
